def _get_status_description(code: int | None, org_type: str | None = None) -> str | None:
    """Получение описания статус-кода."""
    if code is None or org_type is None:
        return None
    description = STATUS_CODE_DESCRIPTIONS.get((code, org_type))
    if description:
        return description
    for (c, _), desc in STATUS_CODE_DESCRIPTIONS.items():
        if c == code:
            return desc
    return None


def _convert_date_to_timestamp(date_str: str | None) -> int | None:
    """Конвертация даты из строки в timestamp (milliseconds)."""
    if not date_str:
        return None
    try:
        # Dadata возвращает дату в формате YYYY-MM-DD
        from datetime import datetime

        dt = datetime.strptime(date_str, "%Y-%m-%d")
        return int(dt.timestamp() * 1000)
    except (ValueError, TypeError):
        return None


class DadataService:
    """Сервис для работы с API Dadata (поиск организаций по ИНН)."""

    def __init__(self) -> None:
        self._api_key = settings.DADATA_API_KEY
        self._url = "https://suggestions.dadata.ru/suggestions/api/4_1/rs/findById/party"
        self._client: httpx.AsyncClient | None = None
        self._cache_expire = 86400  # 24 часа

    async def _get_client(self) -> httpx.AsyncClient:
        """Получение или создание HTTP клиента."""
        if self._client is None or self._client.is_closed:
            self._client = httpx.AsyncClient(
                timeout=httpx.Timeout(10.0),
                headers={
                    "Content-Type": "application/json",
                    "Accept": "application/json",
                    "Authorization": f"Token {self._api_key}",
                },
            )
        return self._client

    async def find_by_inn(self, inn: str, redis: Redis) -> InnLookupResult | None:
        """
        Поиск организации по ИНН.

        Args:
            inn: ИНН организации (10 или 12 цифр).
            redis: Redis клиент для кэшированию.

        Returns:
            InnLookupResult с данными организации или None если не найдено.
        """
        # Проверка кэша
        cache_key = f"dadata:inn:{inn}"
        cached_data = await redis.get(cache_key)
        if cached_data:
            return InnLookupResult.model_validate_json(cached_data)

        # Запрос к API
        client = await self._get_client()
        try:
            response = await client.post(self._url, json={"query": inn, "count": 1})
            response.raise_for_status()
        except Exception:
            return None

        data = response.json()
        suggestions = data.get("suggestions", [])
        if not suggestions:
            return None

        # Парсинг и бизнес-валидация
        result = self._parse_suggestion(suggestions[0])

        # Сохранение в кэш
        await redis.set(cache_key, result.model_dump_json(), ex=self._cache_expire)

        return result

    def _parse_suggestion(self, suggestion: dict[str, Any]) -> InnLookupResult:
        """Парсинг ответа от Dadata API."""
        data: dict[str, Any] = suggestion.get("data", {})
        state: dict[str, Any] = data.get("state", {})
        status = state.get("status", "ACTIVE")
        status_code = state.get("code")

        # Логика предупреждений (Бизнес-аналитика)
        is_warning = False
        warning_message = None
        if status == "LIQUIDATING":
            is_warning = True
            warning_message = "Организация находится в стадии ликвидации"
        elif status in ("LIQUIDATED", "BANKRUPT"):
            is_warning = True
            warning_message = "Организация ликвидирована или признана банкротом"

        is_individual = data.get("type") == "INDIVIDUAL"
        org_type = "INDIVIDUAL" if is_individual else "LEGAL"

        # Извлекаем ФИО руководителя или ИП
        ceo_name = data.get("management", {}).get("name") if not is_individual else data.get("fio", {}).get("name")
        if is_individual and not ceo_name:
            # Для ИП ФИО часто лежит прямо в value
            ceo_name = suggestion.get("value")

        # Извлекаем город из адреса
        address_data: dict[str, Any] = data.get("address", {})
        city = None
        if address_data:
            city = address_data.get("data", {}).get("city") or address_data.get("data", {}).get("settlement")

        # Извлекаем ОКВЕД
        okved = None
        okved_data = data.get("okved")
        if okved_data and isinstance(okved_data, dict):
            okved_type = okved_data.get("type")
            okved_name = okved_data.get("name")
            if okved_type and okved_name:
                okved = f"{okved_type} - {okved_name}"

        # Извлекаем телефоны и emails
        phones: list[str] = []
        emails: list[str] = []
        contact_data = data.get("contact", {})
        if contact_data:
            phones = contact_data.get("phones", []) or []
            emails = contact_data.get("emails", []) or []

        # Конвертация дат
        registration_date = _convert_date_to_timestamp(state.get("registration_date"))
        liquidation_date = _convert_date_to_timestamp(state.get("liquidation_date"))

        # Получение описания статус-кода
        status_description = _get_status_description(status_code, org_type)

        return InnLookupResult(
            inn=data.get("inn"),
            kpp=data.get("kpp"),
            ogrn=data.get("ogrn"),
            full_name=data.get("name", {}).get("full_with_opf") or suggestion.get("value"),
            short_name=data.get("name", {}).get("short_with_opf") or suggestion.get("value"),
            legal_form=data.get("name", {}).get("short"),
            is_individual=is_individual,
            status=status,
            status_code=status_code,
            status_description=status_description,
            is_warning=is_warning,
            warning_message=warning_message,
            registration_date=registration_date,
            liquidation_date=liquidation_date,
            address=address_data.get("value"),
            city=city,
            ceo_name=ceo_name,
            ceo_post=data.get("management", {}).get("post") if not is_individual else "Индивидуальный предприниматель",
            okved=okved,
            phones=phones,
            emails=emails,
        )


